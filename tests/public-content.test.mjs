// An empty scratch repository, a git that runs in it, a commit helper that
// writes, removes and commits files, and the check run there.
function repository(t) {
  const dir = tempDir(t);
  const git = (...args) =>
    execFileSync("git", args, {
      cwd: dir,
      encoding: "utf8",
      env: {
        ...process.env,
        GIT_CONFIG_GLOBAL: "/dev/null",
        GIT_AUTHOR_NAME: "Test",
        GIT_AUTHOR_EMAIL: "test@example.com",
        GIT_COMMITTER_NAME: "Test",
        GIT_COMMITTER_EMAIL: "test@example.com",
      },
    }).trim();
  git("init", "-q", "-b", "main");
  git("config", "commit.gpgsign", "false");
  const commit = (message, files = {}, remove = []) => {
    for (const [name, content] of Object.entries(files)) {
      fs.mkdirSync(path.dirname(path.join(dir, name)), { recursive: true });
      fs.writeFileSync(path.join(dir, name), content);
    }
    for (const name of remove) git("rm", "-q", name);
    git("add", "-A");
    git("commit", "-q", "--allow-empty", "-m", message);
  };
  const check = (...argv) => {
    const cwd = process.cwd();
    process.chdir(dir);
    try {
      return run(argv);
    } finally {
      process.chdir(cwd);
    }
  };
  return { git, commit, check };
}

test("checks the lines a range adds to files", (t) => {
  const { git, commit, check } = repository(t);
  commit("chore: base", { "notes.md": "old\nfrom /home/alice/old\n", "gone.md": "/Users/sam/x\n" });
  git("tag", "base");
  commit(
    "feat: add",
    {
      "notes.md": "old\nfrom /home/alice/old\nnew line\nsee /Users/sam/GitHub\n",
      "docs/sunrise-app.md": "Signed-off-by: Sam <sam@mailbox.test>\n",
      "logo.png": Buffer.from("\x89PNG\x00/Users/sam/x\n", "latin1"),
      // The check's own script and tests hold the patterns they find.
      ".github/scripts/public-content.mjs": "// /Users/sam/x\n",
      "tests/public-content.test.mjs": "// /Users/sam/x\n",
    },
    ["gone.md"],
  );
  const [code, out] = check("--files=base..main");
  assert.equal(code, 1, out);
  const head = git("rev-parse", "--short=7", "main");
  assert.ok(
    out.includes(
      `::error title=Public repository content::commit ${head}, file notes.md, line 4: ` +
        "a local or project-storage path",
    ),
    out,
  );
  // A file whose name has a finding is not named but numbered as
  // `git show --name-only` lists it; its lines are still checked.
  for (const finding of [
    "name: a private repository name",
    "line 1: an email address other than a noreply one",
  ])
    assert.ok(out.includes(`commit ${head}, changed file 2 (name not shown), ${finding}`), out);
  // Not the old line, the removed file, the image or the exempt files.
  assert.equal(out.match(/::error/g).length, 3, out);
  assert.doesNotMatch(out, /sunrise|sam/i);
});

test("reads files commit by commit", (t) => {
  const { git, commit, check } = repository(t);
  commit("chore: base", { "a.md": "from /home/alice/x\n" });
  git("switch", "-q", "-c", "topic");
  commit("feat: rename", { "b.md": "from /home/alice/x\n" }, ["a.md"]);
  commit("feat: clean line", { "c.md": "nothing private\n" });
  let [code, out] = check("--files=main..topic");
  assert.equal(code, 0, out); // a rename adds no lines
  assert.match(out, /No private details found in 0 text\(s\) and 2 file change\(s\)\./);
  // A line one commit adds stays in that commit when a later one drops it.
  commit("feat: add a path", { "c.md": "nothing private\nin /Volumes/Work\n" });
  const added = git("rev-parse", "--short=7", "HEAD");
  commit("fix: drop it", { "c.md": "nothing private\n" });
  [code, out] = check("--files=main..topic");
  assert.equal(code, 1, out);
  assert.equal(out.match(/::error/g).length, 1, out);
  assert.ok(
    out.includes(`commit ${added}, file c.md, line 2: a local or project-storage path`),
    out,
  );
  [code, out] = check("--files=topic^!");
  assert.equal(code, 0, out);
});

test("reads a merge for the lines no parent has", (t) => {
  const { git, commit, check } = repository(t);
  commit("chore: base", { "a.md": "one\ntwo\n" });
  git("switch", "-q", "-c", "topic");
  commit("feat: topic", { "a.md": "one\ntwo\ntopic\n" });
  git("switch", "-q", "main");
  commit("fix: main", { "a.md": "main /Users/sam/x\none\ntwo\n", "m.md": "/Users/sam/y\n" });
  git("switch", "-q", "topic");
  git("merge", "-q", "--no-commit", "main");
  // The merge brings main's lines, which main's own run checks, and adds one
  // that neither side has.
  commit("Merge branch 'main' into topic", {
    "a.md": "main /Users/sam/x\none\ntwo\ntopic\nby hand /Volumes/Work\n",
  });
  const merge = git("rev-parse", "--short=7", "HEAD");
  const [code, out] = check("--files=main..topic");
  assert.equal(code, 1, out);
  assert.equal(out.match(/::error/g).length, 1, out);
  assert.ok(
    out.includes(`commit ${merge}, file a.md, line 5: a local or project-storage path`),
    out,
  );
});

