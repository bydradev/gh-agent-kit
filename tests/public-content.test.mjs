// The runner prints a step's env values in the job log, which is public in a
// public repository and keeps the text as it was when the run fired; an
// expression in run: is printed too, and is a script injection besides. So
// no step this repository owns takes a pull request's or issue's title or
// body (or a comment's) from an expression: it reads the event file. The
// workflows gh-repo-bootstrapper owns (pr-title-check.yml and the release
// workflows, stamped template-owned) are checked there.
test("no workflow this repository owns puts event text in an expression", () => {
  const dir = path.join(root, ".github/workflows");
  const files = fs
    .readdirSync(dir)
    .filter((f) => /\.ya?ml$/.test(f))
    .map((f) => path.join(dir, f))
    .filter((f) => !/gh-repo-bootstrapper: template-owned/.test(fs.readFileSync(f, "utf8")));
  assert.ok(files.some((f) => f.endsWith("public-content.yml")));
  assert.ok(files.some((f) => f.endsWith("pr-review.yml")));
  // The whole event or an object of it (toJSON, an index), or an event path
  // through a title or body unless the expression only tests it against null.
  const leaks = (text) =>
    [...text.matchAll(/\$\{\{([\s\S]*?)\}\}/g)].flatMap(([whole, expr], _, all) =>
      [...expr.matchAll(/\bgithub\.event(?!\w)((?:\.\w+)*)(\s*\[)?/g)]
        .filter(
          (m) =>
            !m[1] ||
            m[2] ||
            /toJSON\(\s*$/i.test(expr.slice(0, m.index)) ||
            (m[1].split(".").some((part) => part === "title" || part === "body") &&
              !/^\s*[!=]=\s*null\b/.test(expr.slice(m.index + m[0].length))),
        )
        .map(() => text.slice(0, text.indexOf(whole)).split("\n").length),
    );
  for (const leak of [
    "BODY: ${{ github.event.pull_request.body }}",
    "T: ${{ github.event.issue.title || 'x' }}",
    "C: ${{ github.event.comment.body }}",
    "E: ${{ toJSON(github.event) }}",
    "P: ${{ toJSON(github.event.pull_request) }}",
    "B: ${{ github.event.pull_request['body'] }}",
    "B: ${{\n  github.event.pull_request.body\n}}",
  ]) {
    assert.ok(leaks(leak).length, leak);
  }
  for (const safe of [
    "X: ${{ github.event.changes.title != null && 'a' }}",
    "N: ${{ github.event.pull_request.number }}",
    "E: ${{ github.event_name }}",
    "V: ${{ toJSON(vars) }}",
  ]) {
    assert.deepEqual(leaks(safe), [], safe);
  }
  for (const file of files) {
    assert.deepEqual(
      leaks(fs.readFileSync(file, "utf8")).map((line) => `${path.basename(file)}:${line}`),
      [],
    );
  }
});

